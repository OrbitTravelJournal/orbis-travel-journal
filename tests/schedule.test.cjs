const assert = require('node:assert/strict');
require('../schedule.js');
const S = globalThis.OrbisSchedule;
const stop = (name, lat, lng, length = '60m', extra = {}) => {
  const item = ['09:00', 'Activity', name, '', length, { coordinates: [lat, lng], ...extra }];
  item[5].locationKey = S.locationKey(item, day);
  return item;
};
const day = { city: 'Kyoto', country: 'Japan', planStart: '09:00', items: [] };
const a = stop('A', 35, 135), b = stop('B', 35.005, 135), c = stop('C', 35.1, 135);
day.items = [a, b, c];
let rows = S.plan(day);
assert.equal(rows[1].start, 600 + S.leg(a, b, day).minutes);
assert.equal(rows[2].start, rows[1].end + S.leg(b, c, day).minutes);
const oldTravel = rows[1].travel.minutes;
day.items = [a, c, b];
assert.notEqual(S.plan(day)[1].travel.minutes, oldTravel, 'reorder recalculates adjacent travel');
c[5].travelMode = 'walking';
assert.ok(S.leg(a, c, day).minutes > oldTravel, 'mode affects estimates');
c[2] = 'New location';
assert.equal(S.leg(a, c, day).minutes, null, 'location edits invalidate old coordinates');
assert.equal(S.plan(day)[2].start, null, 'unknown routes never produce invented recommendations');
day.items = [a, b]; b[5].opens = '11:00';
assert.equal(S.plan(day)[1].start, 660);
b[5].closes = '11:30';
assert.match(S.plan(day)[1].conflict, /closing/);
b[5].opens = ''; b[5].closes = ''; b[5].fixedTime = true; b[0] = '09:30';
assert.equal(S.plan(day)[1].start, 570);
assert.match(S.plan(day)[1].conflict, /fixed/);
assert.equal(S.duration(['', 'Activity', '', '', '1h 30m']), 90);
assert.equal(S.clock(1500), '+1 day 01:00');
console.log('Schedule checks passed: reorder, edits, travel modes, unknown locations, opening hours, fixed reservations.');
